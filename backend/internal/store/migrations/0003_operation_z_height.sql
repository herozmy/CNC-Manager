-- 0003_operation_z_height.sql —— 工序增加「Z 轴高度垫高」
--
-- 现场含义：
--   装夹时零件基准面没有直接落在卡盘端面 / 工作台面上，中间垫了一块垫块
--   （或用了对刀块），这个垫块的高度直接影响 Z 向对刀零点。
--   编程员算出的 Z 值是按理论位置给的，操作工必须知道实际垫了多高才能对上刀，
--   漏记这个数值现场就得重新对刀，严重时直接撞刀。
--
-- 单位 mm，沿用 0001 的全库约定：以「实际值 × 1000」的整数落库。
-- 例如垫高 25.5mm 存 25500。

ALTER TABLE operation ADD COLUMN z_height_milli INTEGER NOT NULL DEFAULT 0;
